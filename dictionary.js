/**
 * Smart lookup function: resolves collocations first, then direct words,
 * then morphological stems, with complete fallback safety.
 */
window.lookupWord = function(rawText, sentenceContext) {
  if (!rawText) return null;
  const clean = rawText.toLowerCase().replace(/[^a-z0-9'\s-]/g, '').trim();
  if (!clean) return null;

  // 1. Check if this token belongs to any known collocation in sentence context
  if (sentenceContext) {
    const sLower = sentenceContext.toLowerCase();
    for (const c of window.BRITISH_COLLOCATIONS) {
      if (sLower.includes(c.en.toLowerCase())) {
        const parts = c.en.toLowerCase().split(/\s+/);
        if (parts.includes(clean) || c.en.toLowerCase() === clean) {
          return {
            term: c.en,
            meaning: c.pt,
            ipa: c.ipa || '',
            note: c.note || 'Colocação britânica de prestígio.',
            isCollocation: true
          };
        }
      }
    }
  }

  // 2. Direct Collocation match
  const directColloc = window.BRITISH_COLLOCATIONS.find(c => c.en.toLowerCase() === clean);
  if (directColloc) {
    return {
      term: directColloc.en,
      meaning: directColloc.pt,
      ipa: directColloc.ipa || '',
      note: directColloc.note || '',
      isCollocation: true
    };
  }

  // 3. Direct Dictionary match
  if (window.BRITISH_DICTIONARY[clean]) {
    const d = window.BRITISH_DICTIONARY[clean];
    return {
      term: rawText.trim(),
      meaning: typeof d === 'string' ? d : d.pt,
      ipa: d.ipa || '',
      pos: d.pos || '',
      note: d.note || ''
    };
  }

  // 4. Morphological stemming (e.g. plurals, past tense, continuous, adverbs)
  const stems = [
    clean.replace(/ing$/, ''),
    clean.replace(/ed$/, ''),
    clean.replace(/es$/, ''),
    clean.replace(/s$/, ''),
    clean.replace(/ly$/, '')
  ];

  for (const st of stems) {
    if (st && st.length >= 3 && window.BRITISH_DICTIONARY[st]) {
      const d = window.BRITISH_DICTIONARY[st];
      return {
        term: rawText.trim(),
        meaning: typeof d === 'string' ? d : d.pt,
        ipa: d.ipa || '',
        pos: d.pos || '',
        note: "Derivado de '" + st + "'."
      };
    }
  }

  // 5. Check Master Lexicon
  if (window.MASTER_LEXICON) {
    const foundLex = window.MASTER_LEXICON.find(l => l.term.toLowerCase() === clean);
    if (foundLex) {
      return {
        term: foundLex.term,
        meaning: foundLex.meaning,
        note: "Dia " + foundLex.day + ": " + foundLex.lessonTitle
      };
    }
  }

  // 6. Universal Clean Default Fallback
  return {
    term: rawText.trim(),
    meaning: "Expressão do roteiro britânico.",
    note: "Alterne para o 'Modo Frase a Frase' para ler a tradução exata em português desta sentença."
  };
};
